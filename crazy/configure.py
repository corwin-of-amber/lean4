"""Generate checked-in WASIX build settings from platform.json."""
import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
parser.add_argument('--special-version', action='store_true')
args = parser.parse_args()
config = json.loads((ROOT / 'crazy/platform.json').read_text())
version, _, special = config['release'].partition('-')
major, minor, patch = version.split('.')
if args.special_version:
    print(special)
    raise SystemExit(0)
headers = f'''#pragma once
#define LEAN_VERSION_MAJOR {major}
#define LEAN_VERSION_MINOR {minor}
#define LEAN_VERSION_PATCH {patch}
#define LEAN_VERSION_IS_RELEASE 1
#define LEAN_SPECIAL_VERSION_DESC "{special}"
#define LEAN_VERSION_STRING "{config['release']}"
#define LEAN_PLATFORM_TARGET "{config['target']}"
#define LEAN_MANUAL_ROOT "https://lean-lang.org/doc/reference/{config['release']}/"
'''
outputs = {
    'crazy/include/lean/version.h': headers,
    'crazy/include/githash.h': '// Generated by crazy/configure.py; upstream release identity.\n#define LEAN_GITHASH "' + config['upstreamCommit'] + '"\n',
    'crazy/platform.mk': '# Generated by crazy/configure.py.\nWASMER_STACK_SIZE ?= ' + str(config['wasmerStackSize']) + '\n',
}
for name, contents in outputs.items():
    path = ROOT / name
    if args.check:
        if not path.exists() or path.read_text() != contents:
            raise SystemExit(f'{name} is stale; run python3 crazy/configure.py')
    elif not path.exists() or path.read_text() != contents:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)
if not args.check:
    provenance = dict(config)
    provenance['portCommit'] = subprocess.check_output(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], text=True).strip()
    provenance['modified'] = bool(subprocess.check_output(['git', '-C', str(ROOT), 'status', '--porcelain', '--untracked-files=no'], text=True))
    (ROOT / 'lib').mkdir(exist_ok=True)
    (ROOT / 'lib/build-info.json').write_text(json.dumps(provenance, indent=2) + '\n')
